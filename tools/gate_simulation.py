"""Measure how often the compare-runs gate gives each verdict, by simulation.

Each trial draws baseline and candidate repetitions from a normal distribution with a
known coefficient of variation and a known true throughput change, then runs the real
decision function. The output is the Markdown table in docs/gate-calibration.md:

    python tools/gate_simulation.py > docs/gate-calibration.md

The same function backs tests/test_gate.py, which checks a few rows at a smaller
trial count so the published claims cannot drift from the code.
"""

from __future__ import annotations

import argparse
import random
from collections import Counter

from inference_doctor.quality import QualityThresholds, decide_regression

DEFAULT_SEED = 20261011
REPETITIONS = (3, 5, 10)
CVS = (2.0, 4.0, 8.0)
DROPS = (0.0, 5.0, 10.0, 15.0, 20.0)


def verdict_rates(
    repetitions: int,
    cv_percent: float,
    true_drop_percent: float,
    *,
    trials: int,
    seed: int = DEFAULT_SEED,
    thresholds: QualityThresholds | None = None,
) -> dict[str, float]:
    """Percentage of PASS, FAIL and INCONCLUSIVE verdicts for one scenario.

    The metric is a throughput (higher is better) with a baseline mean of 1000; the
    candidate mean is lower by `true_drop_percent`. Both sides have the same CV.
    """
    thresholds = thresholds or QualityThresholds()
    rng = random.Random(f"{seed}-{repetitions}-{cv_percent}-{true_drop_percent}")
    baseline_mean = 1000.0
    candidate_mean = baseline_mean * (1 - true_drop_percent / 100)
    counts: Counter[str] = Counter()
    for _ in range(trials):
        baseline = [
            rng.gauss(baseline_mean, baseline_mean * cv_percent / 100) for _ in range(repetitions)
        ]
        candidate = [
            rng.gauss(candidate_mean, candidate_mean * cv_percent / 100) for _ in range(repetitions)
        ]
        decision = decide_regression(
            baseline, candidate, lower_is_better=False, thresholds=thresholds
        )
        counts[decision.status] += 1
    return {status: 100 * counts[status] / trials for status in ("PASS", "FAIL", "INCONCLUSIVE")}


def markdown_table(trials: int, seed: int) -> str:
    thresholds = QualityThresholds()
    lines = [
        "# Gate calibration",
        "",
        "How often `compare-runs` returns each verdict when the truth is known. Generated by",
        "`python tools/gate_simulation.py > docs/gate-calibration.md`; `tests/test_gate.py` checks",
        "the same numbers at a smaller trial count.",
        "",
        "Setup: default thresholds (regression "
        f"{thresholds.regression_percent:g}%, {thresholds.confidence:.0%} confidence "
        "interval, no CV ceiling). Each",
        "side has the stated number of repetitions drawn from a normal distribution with the",
        "stated coefficient of variation (CV). The true drop is the real throughput loss of the",
        f"candidate. {trials:,} trials per row, seed {seed}.",
        "",
        "Reading the table: with a true drop below 10%, every FAIL is a false alarm; with a",
        "true drop above 10%, every PASS is a missed regression. A true drop of exactly 10%",
        "sits on the threshold, so INCONCLUSIVE is the right answer there. INCONCLUSIVE",
        "elsewhere is the cost of noise, and more repetitions reduce it.",
        "",
        "What the table shows:",
        "",
        "- Wrong verdicts are bounded by the confidence level. At the threshold itself, PASS",
        "  and FAIL each occur about 5% of the time, (1 - 0.90) / 2. Away from the threshold",
        "  they fall to well under 1%: no row with a true drop of 5% or less FAILs more than",
        "  0.5% of the time, and no row with a true drop of 15% or more PASSes more than 0.5%.",
        "- Noise costs decisions, not correctness. A noisy benchmark gets INCONCLUSIVE more",
        "  often instead of a confident wrong answer.",
        "- Use 5 or more repetitions per side. With 3, a healthy benchmark at 4% CV and no",
        "  change is INCONCLUSIVE about a fifth of the time; with 5, about 2%.",
        "",
        "These rates assume independent, normally distributed repetitions. Drift between",
        "repetitions, warm-up effects or a bimodal benchmark are not modelled; interleaving",
        "baseline and candidate runs and discarding warm-up runs keeps real data closer to",
        "this assumption.",
        "",
        "| Repetitions per side | CV | True drop | PASS | FAIL | INCONCLUSIVE |",
        "| ---: | ---: | ---: | ---: | ---: | ---: |",
    ]
    for repetitions in REPETITIONS:
        for cv in CVS:
            for drop in DROPS:
                rates = verdict_rates(repetitions, cv, drop, trials=trials, seed=seed)
                lines.append(
                    f"| {repetitions} | {cv:g}% | {drop:g}% | {rates['PASS']:.1f}% | "
                    f"{rates['FAIL']:.1f}% | {rates['INCONCLUSIVE']:.1f}% |"
                )
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--trials", type=int, default=4000)
    parser.add_argument("--seed", type=int, default=DEFAULT_SEED)
    args = parser.parse_args()
    print(markdown_table(args.trials, args.seed), end="")


if __name__ == "__main__":
    main()
